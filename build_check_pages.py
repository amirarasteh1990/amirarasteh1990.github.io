# The three hand-written editions are not in build_read_pages.LANGS.
HAND = {"en": ("English", "English", "/sedaha/read/"),
        "fa": ("Persian", "فارسی", "/sedaha/read/fa/"),
        "da": ("Danish", "Dansk", "/sedaha/read/da/")}

# The Worker's own limits (guestbook-worker/worker.mjs), so a page can never
# offer something the intake refuses.
SLUG_RE = re.compile(r"^[a-z]{2,3}(?:-[a-z]{2,4})?$")
VERSION_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:-]{0,39}$")
ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_./#-]{0,79}$")
MAX_ITEMS = 40
MAX_Q_WORDS = 25
MAX_BEFORE, MAX_BEFORE_CHARS = 4, 420

# 'quoted' words inside a question: a native-script quote is isolated and tagged
# with its language, so an Urdu word cannot drag the English punctuation around it
# and gets its own script's face. A plain-ASCII quote ('car') stays English.
QUOTED = re.compile(r"(?<!\w)'([^']+?)'(?!\w)")


class DataError(ValueError):
    pass


def names(slug: str) -> tuple[str, str, str]:
    """(English name, native name, Opening URL) for an edition slug."""
    if slug in HAND:
        return HAND[slug]
    for L in read.LANGS:
        if L["slug"] == slug:
            return L["en"], L["native"], f"/sedaha/read/{slug}/"
    raise DataError(f"{slug}: no such edition in build_read_pages.LANGS")


def load(path: Path, slug: str | None = None) -> dict:
    """Read and validate one data file (a round file names its slug by its folder)."""
    try:
        d = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise DataError(f"{path.name}: {exc}") from exc
    for key in ("lang", "slug", "dir", "version", "items"):
        if key not in d:
            raise DataError(f"{path.name}: missing '{key}'")
    if d["slug"] != (slug or path.stem) or not SLUG_RE.match(d["slug"]):
        raise DataError(f"{path.name}: slug must be the file name, as on /sedaha/read/")
    if d["dir"] not in ("ltr", "rtl"):
        raise DataError(f"{path.name}: dir must be ltr or rtl")
    if not VERSION_RE.match(str(d["version"])):
        raise DataError(f"{path.name}: version must be a short token like 2026-11-16")
    items = d["items"]
    if not isinstance(items, list) or not 1 <= len(items) <= MAX_ITEMS:
        raise DataError(f"{path.name}: between 1 and {MAX_ITEMS} items")
    seen = set()
    for n, it in enumerate(items, 1):
        where = f"{path.name} item {n}"
        for key in ("id", "where", "text", "q"):
            if not isinstance(it.get(key), str) or not it[key].strip():
                raise DataError(f"{where}: missing '{key}'")
        if not ID_RE.match(it["id"]) or not it["id"].startswith(it["where"] + "#"):
            raise DataError(f"{where}: id must be '<where>#<n>' ({it['id']!r})")
        if it["id"] in seen:
            raise DataError(f"{where}: duplicate id {it['id']!r}")
        seen.add(it["id"])
        if len(it["q"].split()) > MAX_Q_WORDS:
            raise DataError(f"{where}: question longer than {MAX_Q_WORDS} words")
        before = it.get("before", [])
        if (not isinstance(before, list) or len(before) > MAX_BEFORE
                or not all(isinstance(b, str) and b.strip() and len(b) <= MAX_BEFORE_CHARS
                           for b in before)):
            raise DataError(f"{where}: 'before' must be up to {MAX_BEFORE} lines "
                            f"of at most {MAX_BEFORE_CHARS} characters")
    names(d["slug"])
    return d


def _q_html(q: str, lang: str, dir_: str) -> str:
    out, last = [], 0
    for m in QUOTED.finditer(q):
        out.append(html.escape(q[last:m.start()], quote=False))
        inner = m.group(1)
        if inner.isascii():
            out.append(html.escape(m.group(0), quote=False))
        else:
            out.append(f"'<bdi lang=\"{lang}\" dir=\"{dir_}\">"
                       f"{html.escape(inner, quote=False)}</bdi>'")
        last = m.end()
    out.append(html.escape(q[last:], quote=False))
    return "".join(out)


def _item_html(n: int, it: dict, lang: str, dir_: str) -> str:
    e = lambda s: html.escape(s, quote=False)  # noqa: E731
    ctx = "".join(f'        <p class="nc-ctx">{e(b)}</p>\n' for b in it.get("before", []))
    return f"""    <fieldset class="nc-item" data-id="{html.escape(it['id'], quote=True)}">
      <legend>Line {n}</legend>
      <div class="reader nc-text" lang="{lang}" dir="{dir_}">
{ctx}        <p class="nc-line">{e(it['text'])}</p>
      </div>
      <p class="nc-q" id="q{n}">{_q_html(it['q'], lang, dir_)}</p>
      <div class="nc-verdict" role="radiogroup" aria-labelledby="q{n}">
        <label><input type="radio" name="v{n}" value="ok"> Correct</label>
        <label><input type="radio" name="v{n}" value="change"> Needs change</label>
        <label><input type="radio" name="v{n}" value="unsure"> Not sure</label>
      </div>
      <p class="guestbook-field">
        <label for="n{n}">How would you say it? <span class="nc-optional">(optional)</span></label>
        <textarea id="n{n}" name="n{n}" rows="2" maxlength="600" dir="auto"></textarea>
      </p>
    </fieldset>"""


