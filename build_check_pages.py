ROUNDS_DIR = DATA_DIR / "rounds"


def data_rounds() -> dict[str, list[tuple[int, Path]]]:
    """Later rounds of a language's questions: data/native_check/rounds/<slug>/<n>.json, n = 2, 3, ...
    with no gaps (round 1 is data/native_check/<slug>.json). A round without round 1 is ignored."""
    out = {}
    for d in sorted(ROUNDS_DIR.iterdir()) if ROUNDS_DIR.is_dir() else []:
        if not d.is_dir() or not (DATA_DIR / f"{d.name}.json").is_file():
            continue
        ns = sorted((int(p.stem), p) for p in d.glob("*.json") if p.stem.isdigit())
        ns = [x for i, x in enumerate(ns) if x[0] == i + 2]   # stop at the first gap
        if ns:
            out[d.name] = ns
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="report drift only; change nothing; exit 1 if stale")
    args = ap.parse_args()

    ok, wanted, wanted_rounds = True, set(), set()
    rounds = data_rounds()
    jobs = [(p, None, 1) for p in (sorted(DATA_DIR.glob("*.json")) if DATA_DIR.is_dir() else [])]
    jobs += [(p, slug, n) for slug, ps in rounds.items() for n, p in ps]
    for path, rslug, rnd in jobs:
        try:
            d = load(path, rslug)
        except DataError as exc:
            print(f"[drift] {exc}")
            ok = False
            continue
        total = 1 + len(rounds.get(d["slug"], []))
        if rnd == 1:
            wanted.add(d["slug"])
            dest = OUT_DIR / d["slug"] / "index.html"
            src = f"data/native_check/{path.name}"
        else:
            wanted_rounds.add((d["slug"], str(rnd)))
            dest = OUT_DIR / d["slug"] / str(rnd) / "index.html"
            src = f"data/native_check/rounds/{d['slug']}/{path.name}"
        page = render(d, src, rnd, total)
        rel = dest.relative_to(SITE).as_posix()
        if dest.is_file() and dest.read_text(encoding="utf-8") == page:
            continue
        if args.check:
            print(f"[drift] {rel}: missing or stale")
            ok = False
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(page, encoding="utf-8", newline="\n")
        print(f"[write] {rel}  ({len(d['items'])} lines)")

    # a round page whose data file is gone
    for dest in sorted(OUT_DIR.glob("*/*/index.html")) if OUT_DIR.is_dir() else []:
        key = (dest.parent.parent.name, dest.parent.name)
        if key in wanted_rounds or GENERATED not in dest.read_text(encoding="utf-8"):
            continue
        rel = dest.relative_to(SITE).as_posix()
        if args.check:
            print(f"[drift] {rel}: no round data any more")
            ok = False
            continue
        dest.unlink()
        try:
            dest.parent.rmdir()
        except OSError:
            pass
        print(f"[write] removed {rel}")

    # a page whose data file is gone; only this script's own output is touched
    for dest in sorted(OUT_DIR.glob("*/index.html")) if OUT_DIR.is_dir() else []:
        slug = dest.parent.name
        if slug in wanted or GENERATED not in dest.read_text(encoding="utf-8"):
            continue
        rel = dest.relative_to(SITE).as_posix()
        if args.check:
            print(f"[drift] {rel}: no data file any more")
            ok = False
            continue
        dest.unlink()
        try:
            dest.parent.rmdir()
        except OSError:
            pass
        print(f"[write] removed {rel}  (no data/native_check/{slug}.json)")

    if ok:
        print(f"[ok]    {len(wanted)} native-check pages in sync"
              + (f", plus {len(wanted_rounds)} round pages" if wanted_rounds else ""))
    return 1 if (args.check and not ok) else 0


if __name__ == "__main__":
    sys.exit(main())
