#!/usr/bin/env python3
"""
build_check_pages.py: the native-speaker check pages, /sedaha/check/<slug>/.

One page per data/native_check/<slug>.json:

    {"lang": "hu", "slug": "hu", "dir": "ltr", "version": "2026-11-16",
     "items": [{"id": "<where>#<n>", "where": "04b/1227",
                "text": "<the sentence, verbatim from the edition>",
                "q": "<a plain English question, at most 25 words>",
                "before": ["<up to 4 lines from just before it, verbatim>"]}]}

Each line is shown in its own language and direction, in the reading pages' own
type (.reader p), after the lines just before it in grey (`before`, optional, so
a reader who has not read the book has the setup), with its question,
Correct / Needs change / Not sure, and an optional note ("How would you say
it?"). A short box at the top says what is kept on purpose (2026-11-22).

Later rounds (2026-11-22): data/native_check/rounds/<slug>/<n>.json (n = 2, 3, ...) become
/sedaha/check/<slug>/<n>/; every page says "Round n of N" and, after sending, links the next round. One Send button posts the answers to the guestbook Worker at /check, which
files them as one `native-check` issue. If that fails for any reason the page
offers the same answers as a prefilled email (assets/js/native-check.js).

The pages are noindex and stay out of the sitemap and the feed. The Opening page
of a language with a data file links here (build_read_pages.native_check_link),
so after adding or removing a data file, run build_read_pages.py as well.

    python build_check_pages.py            (re)write every page, remove orphans
    python build_check_pages.py --check    report drift only; exit 1 if stale
"""
