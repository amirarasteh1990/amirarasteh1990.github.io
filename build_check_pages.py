def load_v2(path: Path, d: dict, slug: str | None) -> dict:
    name = path.name
    for key in ("lang", "slug", "dir", "version", "page", "pages", "first", "strings", "groups"):
        if key not in d:
            raise DataError(f"{name}: missing '{key}'")
    if d["slug"] != (slug or path.stem) or not SLUG_RE.match(d["slug"]):
        raise DataError(f"{name}: slug must be the file name, as on /sedaha/read/")
    if d["dir"] not in ("ltr", "rtl"):
        raise DataError(f"{name}: dir must be ltr or rtl")
    if not VERSION_RE.match(str(d["version"])):
        raise DataError(f"{name}: version must be a short token")
    want_page = 1 if slug is None else int(path.stem)
    if d["page"] != want_page or not 1 <= d["page"] <= d["pages"]:
        raise DataError(f"{name}: page must be {want_page} (of 'pages')")
    st = d["strings"]
    for key in V2_STRINGS:
        if not isinstance(st.get(key), str) or not st[key].strip():
            raise DataError(f"{name}: strings: missing '{key}'")
    for key in ("send_continue", "popup_button", "arrived", "continue_with"):
        if "{n}" not in st[key]:
            raise DataError(f"{name}: strings: '{key}' needs {{n}}")
    if "{email}" not in st["noscript"]:
        raise DataError(f"{name}: strings: 'noscript' needs {{email}}")
    if not d["groups"]:
        raise DataError(f"{name}: no groups")
    seen, rows = set(), 0
    for gi, g in enumerate(d["groups"], 1):
        where = f"{name} group {gi}"
        for key in ("q", "labels", "note_label", "note_on", "rows"):
            if key not in g:
                raise DataError(f"{where}: missing '{key}'")
        if (not isinstance(g["labels"], list) or len(g["labels"]) != 3
                or not all(isinstance(x, str) and x.strip() for x in g["labels"])):
            raise DataError(f"{where}: labels must be 3 answers")
        if g["note_on"] not in ("ok", "change", "unsure"):
            raise DataError(f"{where}: note_on must be ok, change or unsure")
        if not g["rows"]:
            raise DataError(f"{where}: no rows")
        for r in g["rows"]:
            if not isinstance(r.get("text"), str) or not r["text"].strip():
                raise DataError(f"{where}: a row has no text")
            if not ID_RE.match(str(r.get("id", ""))) or r["id"] in seen:
                raise DataError(f"{where}: bad or duplicate id {r.get('id')!r}")
            seen.add(r["id"])
            rows += 1
    if rows > MAX_ROWS:
        raise DataError(f"{name}: {rows} rows; the Worker takes at most {MAX_ROWS}")
    names(d["slug"])
    return d


def _v2_row(k: int, r: dict, g: dict, d: dict) -> str:
    e = lambda s: html.escape(s, quote=False)  # noqa: E731
    st, lang, dir_ = d["strings"], d["lang"], d["dir"]
    note = f'\n      <p class="nc-note">{e(r["note"])}</p>' if r.get("note") else ""
    after = ""
    if g.get("after"):
        after = ('\n      <ul class="nc-after">' + "".join(f"<li>{e(x)}</li>" for x in g["after"])
                 + "</ul>")
        if g.get("after_q"):
            after += f'\n      <p class="nc-q">{e(g["after_q"])}</p>'
    radios = "\n".join(
        f'        <label><input type="radio" name="v{k}" value="{v}"> {e(lab)}</label>'
        for v, lab in zip(("ok", "change", "unsure"), g["labels"]))
    return f"""    <div class="nc-item" role="group" aria-labelledby="l{k}" data-id="{html.escape(r['id'], quote=True)}" data-note-on="{g['note_on']}">
      <div class="reader nc-text" lang="{lang}" dir="{dir_}"><p class="nc-line" id="l{k}">{e(r['text'])}</p></div>{note}{after}
      <div class="nc-verdict" role="radiogroup" aria-labelledby="l{k}">
{radios}
      </div>
      <p class="guestbook-field nc-notebox" hidden>
        <label for="n{k}">{e(g['note_label'])} <span class="nc-optional">{e(st['optional'])}</span></label>
        <textarea id="n{k}" name="n{k}" rows="2" maxlength="600" dir="auto"></textarea>
      </p>
    </div>"""


def _v2_groups(d: dict) -> str:
    e = lambda s: html.escape(s, quote=False)  # noqa: E731
    out, k = [], 0
    for gi, g in enumerate(d["groups"]):
        num = d["first"] + gi
        ql = f' lang="{g["q_lang"]}" dir="ltr"' if g.get("q_lang") and g["q_lang"] != d["lang"] else ""
        if g.get("title"):
            head = (f'    <h2 class="nc-gh" id="g{num}"><span class="nc-num">{num}</span> {e(g["title"])}</h2>\n'
                    f'    <p class="nc-gq"{ql}>{e(g["q"])}</p>')
        else:   # a one-off question: the question is the heading
            head = (f'    <h2 class="nc-gh nc-gh-q" id="g{num}"><span class="nc-num">{num}</span> '
                    f'<span{ql}>{e(g["q"])}</span></h2>')
        rows = []
        for r in g["rows"]:
            k += 1
            rows.append(_v2_row(k, r, g, d))
        out.append(f'  <section class="nc-group" aria-labelledby="g{num}">\n{head}\n'
                   + "\n".join(rows) + "\n  </section>")
    return "\n".join(out)


