/* The language finder on /sedaha/.

   One question, one answer, in one place. The page is a doorway: it holds no list
   of languages at all, so this reads them from window.EDITIONS (generated by
   build_read_pages.py from the GitHub release) and answers under the input.

   Three outcomes, all answered in the same place:
     one language   its name, what exists in it, and the buttons
     several        how many, and up to five to choose from
     none           said plainly, with a way to browse and a way to write

   It also runs the cycling "Read it in ..." line, because both need the same list.
   Needs assets/js/lang-alias.js loaded first for the other names each language
   answers to. */
(function () {
  'use strict';
  var LANGS = window.EDITIONS || [];
  var ALIAS = window.LANG_ALIASES || {};
  var input = document.getElementById('langSearch');
  var result = document.getElementById('langResult');
  if (!input || !result || !LANGS.length) return;

  /* Fold a name to something a keyboard without that language can produce: the
     accents decompose away, and the letters that do not decompose (o with a
     stroke is one character, not o plus a mark) are mapped by hand. So turkce
     finds Türkçe, espanol finds Español, foroyskt finds Føroyskt. */
  var LETTERS = {'ø':'o','æ':'ae','ß':'ss','đ':'d','ð':'d',
                 'þ':'th','ł':'l','ı':'i','œ':'oe','’':"'"};
  function fold(s) {
    s = String(s).toLowerCase().replace(/[øæßđðþłıœ’]/g, function (c) { return LETTERS[c]; });
    return s.normalize ? s.normalize('NFD').replace(/[\u0300-\u036f]/g, '') : s;
  }

  /* What a language is searchable BY: its two names, the other names it answers
     to, and its code. Nothing else -- indexing everything printed beside it meant
     "pdf" matched every complete edition and "opening" matched all of them. */
  LANGS.forEach(function (L) {
    L.hay = fold([L.native, L.en, ALIAS[L.slug] || '', L.slug].join(' '));
    L.first = (ALIAS[L.slug] || '').split(' ')[0];
  });

  var bySlug = {};
  LANGS.forEach(function (L) { bySlug[L.slug] = L; });

  /* The book was published in these three, and they are what a reader whose own
     edition is still coming can have tonight. The same three the opening pages
     offer, for the same reason: an answer that says only "not yet" is not an
     answer. Read from the data, so a language that loses its files drops out. */
  var WHOLE = ['fa', 'en', 'da'].map(function (s) { return bySlug[s]; })
    .filter(function (L) {
      return L && (L.files || []).some(function (f) { return f[0] === 'epub'; });
    });

  /* Typed in full beats typed in part: "german" is German, though it also sits
     inside Low German, and "farsi" is Persian, though Dari answers to it too.
     The first alias in a language's list counts as one of its full names. */
  function exact(L, q) {
    return fold(L.en) === q || fold(L.native) === q || L.slug === q || L.first === q;
  }

  var STATE = {
    ready: 'The complete book is available.',
    review: 'The complete edition is in final review.',
    translated: 'Complete edition in preparation.',
    revising: 'The complete edition is being revised.'
  };

  function el(tag, cls, text) {
    var n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text != null) n.textContent = text;
    return n;
  }

  function nameInto(node, L) {
    var n = el('span', 'native', L.native);
    n.setAttribute('lang', L.lang);
    if (L.rtl) n.setAttribute('dir', 'rtl');
    node.appendChild(n);
    if (L.en !== L.native) {
      node.appendChild(document.createTextNode(' '));
      node.appendChild(el('span', 'en', L.en));
    }
    return node;
  }

  function shareButton(L) {
    var b = el('button', 'btn btn-icon btn-share');
    b.type = 'button';
    b.setAttribute('aria-label', 'Share the ' + L.en + ' opening');
    b.setAttribute('title', 'Share the ' + L.en + ' opening');
    b.setAttribute('data-share-url', 'https://arasteh.art' + L.url);
    b.setAttribute('data-share-title', 'Sedaha — Book One');
    b.innerHTML = '<svg aria-hidden="true" viewBox="0 0 24 24" fill="none" stroke-width="2" ' +
      'stroke-linecap="round" stroke-linejoin="round"><path d="M12 2v13"/>' +
      '<path d="m16 6-4-4-4 4"/><path d="M20 10v9a2 2 0 0 1-2 2H6a2 2 0 0 1-2-2v-9"/></svg>';
    return b;
  }

  /* An edition still on its way used to leave the panel almost empty: a name and
     one button. It can offer more than that without pretending: the whole book
     exists in the three it was published in, and that is what the reader wants
     tonight. Same offer the opening pages make, from the same data. */
  function meanwhile(L) {
    var others = WHOLE.filter(function (o) { return o.slug !== L.slug; });
    if (!others.length) return null;
    var wrap = el('div', 'lr-meanwhile');
    /* Naming only these three read as though only three existed; there are now 23.
       The count comes from the data, so the sentence cannot go stale again. */
    var whole = LANGS.filter(function (L) { return L.files && L.files.length; }).length;
    var note = el('p', 'lr-meanwhile-note', 'Until it is ready, the whole book can be read in ');
    var all = el('a', null, whole + ' other languages');
    all.href = '/sedaha/languages/';
    note.appendChild(all);
    note.appendChild(document.createTextNode(', among them'));
    wrap.appendChild(note);
    var acts = el('p', 'lr-actions');
    others.forEach(function (o) {
      var epub = (o.files || []).filter(function (f) { return f[0] === 'epub'; })[0];
      var a = el('a', 'btn');
      a.href = epub[2];
      a.setAttribute('aria-label', o.en + ', the complete book, EPUB');
      var n = el('span', null, o.native);
      n.setAttribute('lang', o.lang);
      if (o.rtl) n.setAttribute('dir', 'rtl');
      a.appendChild(n);
      a.appendChild(el('span', 'btn-fmt', 'EPUB'));
      acts.appendChild(a);
    });
    wrap.appendChild(acts);
    return wrap;
  }

  function one(L) {
    result.textContent = '';
    result.appendChild(nameInto(el('p', 'lr-name'), L));
    result.appendChild(el('p', 'lr-state',
      'The opening is ready to read. ' + (STATE[L.state] || STATE.translated)));

    var acts = el('p', 'lr-actions');
    var read = el('a', 'btn btn-primary', 'Read the opening');
    read.href = L.url;
    acts.appendChild(read);
    (L.files || []).forEach(function (f) {
      var a = el('a', 'btn', f[0].toUpperCase() + (f[1] ? ' · ' + f[1] : ''));
      a.href = f[2];
      a.setAttribute('aria-label', L.en + ', the complete book, ' + f[0].toUpperCase());
      acts.appendChild(a);
    });
    acts.appendChild(shareButton(L));
    result.appendChild(acts);

    var soon = (L.files && L.files.length) ? null : meanwhile(L);
    if (soon) result.appendChild(soon);

    /* Why a download leaves the site, and what to do if it cannot: shown to anyone
       who has just been offered files, whether their own or the three the book was
       published in. It matters most to readers in Iran and Afghanistan, so it must
       be findable there and invisible where no file has been offered at all. */
    if ((L.files && L.files.length) || soon) {
      var help = document.createElement('details');
      help.className = 'dl-help';
      help.appendChild(el('summary', null, 'Download help'));
      var p = el('p', null, 'EPUB adjusts to your screen. PDF keeps the printed page. ' +
        'The files are hosted on GitHub, so the download opens there. If that is blocked ' +
        'on your network, ');
      var mail = el('a', null, 'write to Amir');
      mail.href = 'mailto:amirarasteh1990@gmail.com?subject=' +
        encodeURIComponent('Sedaha in ' + L.en);
      p.appendChild(mail);
      p.appendChild(document.createTextNode(' and he will send them to you.'));
      help.appendChild(p);
      result.appendChild(help);
    }
    result.hidden = false;
  }

  var SHOW = 5;

  function several(list, q) {
    result.textContent = '';
    result.appendChild(el('p', 'lr-state', list.length + ' languages match “' + q + '”'));
    list.slice(0, SHOW).forEach(function (L) {
      var row = el('p', 'lr-match');
      nameInto(row, L);
      var go = el('a', 'btn', 'Read the opening');
      go.href = L.url;
      row.appendChild(go);
      result.appendChild(row);
    });
    if (list.length > SHOW) {
      var all = el('p', 'lr-actions');
      var a = el('a', 'btn', 'View all matches');
      a.href = '/sedaha/languages/';
      all.appendChild(a);
      result.appendChild(all);
    }
    result.hidden = false;
  }

  function none(q) {
    result.textContent = '';
    result.appendChild(el('p', 'lr-state', 'No language matches “' + q + '”.'));
    var acts = el('p', 'lr-actions');
    var browse = el('a', 'btn', 'Browse all languages');
    browse.href = '/sedaha/languages/';
    var write = el('a', 'btn', 'Write to Amir');
    write.href = 'mailto:amirarasteh1990@gmail.com?subject=' +
      encodeURIComponent('Sedaha in ' + q);
    acts.appendChild(browse);
    acts.appendChild(write);
    result.appendChild(acts);
    result.hidden = false;
  }

  var clearBtn = document.getElementById('langClear');

  function apply() {
    var typed = input.value.trim();
    var q = fold(typed);
    if (clearBtn) clearBtn.hidden = !typed;
    if (!q) { result.hidden = true; result.textContent = ''; return; }
    var hits = LANGS.filter(function (L) { return L.hay.indexOf(q) > -1; });
    var full = hits.filter(function (L) { return exact(L, q); });
    if (full.length === 1) one(full[0]);
    else if (hits.length === 1) one(hits[0]);
    else if (hits.length) several(hits, typed);
    else none(typed);
  }

  input.addEventListener('input', apply);
  input.addEventListener('keydown', function (e) {
    // Escape clears the field, as it does in any search box
    if (e.key === 'Escape' && input.value) { input.value = ''; apply(); }
  });
  if (clearBtn) clearBtn.addEventListener('click', function () {
    input.value = ''; apply(); input.focus();
  });

  /* arasteh.art/sedaha/#ja still answers, so old links keep working */
  function fromHash() {
    var L = bySlug[decodeURIComponent(location.hash.slice(1)).toLowerCase()];
    if (!L) return;
    input.value = L.en;
    apply();
    result.scrollIntoView({block: 'center'});
  }
  fromHash();
  window.addEventListener('hashchange', fromHash);

  /* Quick starts: five languages for someone who would rather not type. Four are
     the author's, generated into the page from the release. The fifth is Chinese
     until the browser tells us something better: a visitor whose own language has
     a COMPLETE edition gets that instead, since a shortcut to an opening they
     cannot finish is not much of a shortcut. Chinese stays for everyone else. */
  (function () {
    var row = document.querySelector('.quick-row');
    if (!row) return;
    var fallback = row.querySelector('[data-slug="' + row.getAttribute('data-fallback') + '"]');
    if (!fallback) return;
    var fixed = [].slice.call(row.querySelectorAll('[data-slug]'))
      .map(function (a) { return a.getAttribute('data-slug'); })
      .filter(function (s) { return s !== fallback.getAttribute('data-slug'); });

    var mine = null;
    var wanted = (navigator.languages || [navigator.language || '']).slice(0, 4);
    for (var i = 0; i < wanted.length && !mine; i++) {
      var tag = String(wanted[i]).toLowerCase().replace('_', '-');
      var found = bySlug[tag] || bySlug[tag.split('-')[0]];
      // only a language that is complete, and not already one of the four
      if (found && found.files && found.files.length && fixed.indexOf(found.slug) < 0) mine = found;
    }
    if (!mine) return;

    var a = el('a', 'lang-box', mine.native);
    a.href = mine.url;
    a.setAttribute('lang', mine.lang);
    if (mine.rtl) a.setAttribute('dir', 'rtl');
    a.setAttribute('data-slug', mine.slug);
    if (mine.en !== mine.native) {
      // the English name follows the native one, hidden, so both are announced and
      // each in its own voice. An aria-label could only have carried one of them.
      a.appendChild(el('span', 'visually-hidden', ' — ' + mine.en));
    }
    fallback.replaceWith(a);
  })();

  /* Every language, built the first time it is asked for. The doorway carries no
     catalogue in its markup: 113 rows are what made the old page a list instead of
     a page. Opened, it is a plain A-Z of names, each going to its own opening; the
     link to the full catalogue stays underneath for files and states. With no
     scripting the summary still opens, and that link is what it shows. */
  (function () {
    var box = document.getElementById('allLangs');
    if (!box) return;
    var built = false;
    box.addEventListener('toggle', function () {
      if (!box.open || built) return;
      built = true;
      var byName = LANGS.slice().sort(function (a, b) {
        var x = fold(a.en), y = fold(b.en);
        return x < y ? -1 : x > y ? 1 : 0;
      });
      var whole = byName.filter(function (L) { return L.files && L.files.length; });
      var partial = byName.filter(function (L) { return !(L.files && L.files.length); });
      var foot = box.querySelector('.all-foot');

      /* The whole book first, then the openings: a reader looking for something to
         finish should not have to pick it out of a hundred that only begin. */
      [[whole, 'The whole book, in ' + whole.length + ' languages'],
       [partial, 'The opening, in ' + partial.length + ' more']].forEach(function (pair) {
        if (!pair[0].length) return;
        var group = el('div', 'all-group');
        group.appendChild(el('p', 'all-group-head', pair[1]));
        var row = el('div', 'all-row');
        pair[0].forEach(function (L) {
          var a = el('a', 'lang-box', L.native);
          a.href = L.url;
          a.setAttribute('lang', L.lang);
          if (L.rtl) a.setAttribute('dir', 'rtl');
          if (L.en !== L.native) a.appendChild(el('span', 'visually-hidden', ' — ' + L.en));
          row.appendChild(a);
        });
        group.appendChild(row);
        box.insertBefore(group, foot);
      });
    });
  })();

  /* The book's promise is that it finds you in your own language, so if the browser
     asks for one this site has, say so once, in a line rather than a box. */
  (function () {
    var offer = document.getElementById('langOffer');
    if (!offer || location.hash) return;
    try { if (localStorage.getItem('sedaha-lang-offer') === 'off') return; } catch (e) {}
    var wanted = (navigator.languages || [navigator.language || '']).slice(0, 4);
    var found = null;
    for (var i = 0; i < wanted.length && !found; i++) {
      var tag = String(wanted[i]).toLowerCase().replace('_', '-');
      found = (tag !== 'en' && bySlug[tag]) || null;
      if (!found && tag.split('-')[0] !== 'en') found = bySlug[tag.split('-')[0]] || null;
    }
    if (!found) return;
    /* If the row above already offers it, saying it again here is the site telling
       the same person the same thing twice. A complete edition lands in the row; an
       opening-only one has no place there, and gets this line instead. */
    if (document.querySelector('.quick-row [data-slug="' + found.slug + '"]')) return;
    offer.appendChild(document.createTextNode('Your language appears to be '));
    var b = document.createElement('b');
    b.textContent = found.native;
    b.setAttribute('lang', found.lang);
    if (found.rtl) b.setAttribute('dir', 'rtl');
    offer.appendChild(b);
    offer.appendChild(document.createTextNode('. '));
    var go = el('a', 'go', 'Read the opening →');
    go.href = found.url;
    offer.appendChild(go);
    var close = el('button', 'lang-clear offer-dismiss');
    close.type = 'button';
    close.setAttribute('aria-label', 'Hide this suggestion');
    close.innerHTML = '<svg aria-hidden="true" viewBox="0 0 24 24"><path d="M6 6l12 12M18 6L6 18"/></svg>';
    close.addEventListener('click', function () {
      offer.hidden = true;
      try { localStorage.setItem('sedaha-lang-offer', 'off'); } catch (e) {}
    });
    offer.appendChild(close);
    offer.hidden = false;
  })();

  /* The cycling line. Atmosphere, not navigation: aria-hidden, unclickable, and
     still under prefers-reduced-motion. Persian first because it is the original,
     then the visitor's own language if this site has it, then the rest shuffled
     once so nothing repeats until every language has had a turn. The slot keeps a
     fixed height so a long name cannot shift the page, and the timer stops while
     the tab is hidden rather than animating into an empty room. */
  (function () {
    var slot = document.getElementById('cyclerName');
    if (!slot) return;
    var still = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)');
    var order = LANGS.slice();
    for (var i = order.length - 1; i > 0; i--) {          // one shuffle, then in order
      var j = Math.floor(Math.random() * (i + 1));
      var t = order[i]; order[i] = order[j]; order[j] = t;
    }
    var mine = null, wanted = (navigator.languages || [navigator.language || '']).slice(0, 2);
    for (var k = 0; k < wanted.length && !mine; k++) {
      mine = bySlug[String(wanted[k]).toLowerCase().split('-')[0]] || null;
    }
    order = order.filter(function (L) { return L.slug !== 'fa' && (!mine || L.slug !== mine.slug); });
    if (mine) order.unshift(mine);
    if (still && still.matches) {                          // one language, no motion
      show(mine || bySlug.fa || order[0]);
      return;
    }
    var at = -1, timer = null;
    function show(L) {
      slot.textContent = L.native;
      slot.setAttribute('lang', L.lang);
      if (L.rtl) slot.setAttribute('dir', 'rtl'); else slot.removeAttribute('dir');
    }
    function step() {
      at = (at + 1) % order.length;
      var next = order[at];
      slot.classList.add('is-out');
      setTimeout(function () { show(next); slot.classList.remove('is-out'); }, 300);
    }
    function run() {
      if (timer) return;
      timer = setInterval(step, 3800);
    }
    function stop() { clearInterval(timer); timer = null; }
    document.addEventListener('visibilitychange', function () {
      if (document.hidden) stop(); else run();
    });
    run();
  })();
})();
